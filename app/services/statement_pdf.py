"""
PDF of the Zakat / Sadaqah statement (English or Urdu), built from a CharityStatement.

It reuses the look of the Zakat certificate (app/services/pdf_generator.py: colours, A4 page, table style).
Urdu needs two things the certificate never had:
  * a font with the Urdu letters: Noto Naskh Arabic (SIL Open Font License, see app/assets/fonts/OFL.txt),
    registered below in two parts (Arabic-script letters, and Latin letters and digits);
  * letter shaping and right-to-left ordering, done per line by arabic-reshaper and python-bidi, because reportlab
    draws glyphs left to right as given.
Lines are short on purpose (labels, table cells); long sentences are written as separate short lines so that no
right-to-left text ever has to be wrapped by reportlab.

The statement lines carry NO notes: a PDF is the kind of file people forward, and notes are personal.
Urdu wording below awaits native-speaker review (UR).
"""
