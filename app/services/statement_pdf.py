URDU_FONT = "NotoNaskhArabic"             # Arabic-script letters
URDU_LATIN = "NotoNaskhArabicLatin"       # digits, Latin letters and punctuation inside Urdu pages
_FONT_FILES = ((URDU_FONT, "NotoNaskhArabic-Regular.ttf"), (URDU_LATIN, "NotoNaskhArabic-Latin-Regular.ttf"))

LANGS = ("en", "ur")

# Characters that need the Urdu font: Arabic-script letters, their presentation forms, and the zero-width joiners.
_ARABIC = re.compile(r"([؀-ۿݐ-ݿﭐ-﷿ﹰ-﻿‌‍]+)")
_RESHAPER = arabic_reshaper.ArabicReshaper(configuration={"delete_harakat": False})
_NUMBER = re.compile(r"\d[\d\-.,:/]*\d|\d")                  # 1,250.50 and 2026-12-31 are one number each
_LRE, _PDF = "\u202a", "\u202c"                              # left-to-right embedding (python-bidi 0.4.2 has no isolates)

