_registered = False


def _register_fonts() -> None:
    global _registered
    if _registered:
        return
    for name, filename in _FONT_FILES:
        pdfmetrics.registerFont(TTFont(name, str(FONT_DIR / filename)))
    _registered = True


# ── text helpers ────────────────────────────────────────────────────────────────────────────────

def money(paisa: int) -> str:
    """Integer paisa to '1,250.50'. Integer arithmetic only."""
    whole, cents = divmod(paisa, 100)
    return f"{whole:,}.{cents:02d}"


def shown_date(d: date, lang: str) -> str:
    return d.isoformat() if lang == "ur" else d.strftime("%d %b %Y")


def visual(text: str, lang: str) -> str:
    """
    Logical text to the order the glyphs must be drawn in. Text without Arabic-script letters is returned unchanged.
    Numbers and dates are kept left to right inside right-to-left lines (without this, 2026-12-31 comes out as
    31-12-2026).
    """
    if not _ARABIC.search(text):
        return text
    text = _NUMBER.sub(lambda m: _LRE + m.group(0) + _PDF, text)
    shown = get_display(_RESHAPER.reshape(text), base_dir="R" if lang == "ur" else "L")
    return shown.replace(_LRE, "").replace(_PDF, "")


def markup(text: str, lang: str) -> str:
    """
    Logical text to Paragraph markup. Arabic-script runs are shaped and put in visual order (base direction follows
    the language) and set in the Urdu font; on Urdu pages everything else uses the Latin part of the same font family.
    """
    text = visual(str(text), lang)
    out = []
    for part in _ARABIC.split(text):
        if not part:
            continue
        if _ARABIC.fullmatch(part):
            out.append(f'<font name="{URDU_FONT}">{escape(part)}</font>')
        elif lang == "ur":
            out.append(f'<font name="{URDU_LATIN}">{escape(part)}</font>')
        else:
            out.append(escape(part))
    return "".join(out)


def _style(name, lang, size=10, bold=False, color=BLACK, align=None, leading=None, **kw):
    rtl = lang == "ur"
    font = URDU_LATIN if rtl else ("Helvetica-Bold" if bold else "Helvetica")
    return ParagraphStyle(name, fontName=font, fontSize=size, textColor=color, leading=leading or size * 1.45,
                          alignment=align if align is not None else (TA_RIGHT if rtl else TA_LEFT), **kw)


# ── the document ────────────────────────────────────────────────────────────────────────────────

def build_statement_pdf(statement: CharityStatement, *, lang: str = "en", issued_to: str = "",
                        generated_on: date) -> bytes:
    if lang not in LANGS:
        raise ValueError("lang must be 'en' or 'ur'")
    _register_fonts()
    rtl = lang == "ur"
    t = T[lang]
    P = lambda text, style: Paragraph(markup(text, lang), style)          # noqa: E731
    cell = _style("cell", lang, 9.5)
    cell_num = _style("cell_num", lang, 9.5, align=TA_RIGHT if not rtl else TA_LEFT)
    head = _style("head", lang, 9.5, bold=True, color=WHITE)
    head_num = _style("head_num", lang, 9.5, bold=True, color=WHITE, align=TA_RIGHT if not rtl else TA_LEFT)
    bold_cell = _style("bold_cell", lang, 10, bold=True, color=GREEN_DARK)
    bold_num = _style("bold_num", lang, 10, bold=True, color=GREEN_DARK, align=TA_RIGHT if not rtl else TA_LEFT)

    def row(*cells):
        """Left-to-right column order for English, mirrored for Urdu."""
        return list(reversed(cells)) if rtl else list(cells)

    def widths(*w):
        return [x * cm for x in (reversed(w) if rtl else w)]

    def table(data, col_widths, extra=()):
        tb = Table(data, colWidths=col_widths, repeatRows=1)
        tb.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), GREEN_DARK), ("GRID", (0, 0), (-1, -1), 0.5, GREEN_BORDER),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, GRAY_LIGHT]), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("LEFTPADDING", (0, 0), (-1, -1), 7), ("RIGHTPADDING", (0, 0), (-1, -1), 7), *extra,
        ]))
        return tb

    period_last = statement.date_to - timedelta(days=1)                    # shown as an inclusive last day
    period = t["from_to"].format(a=shown_date(statement.date_from, lang), b=shown_date(period_last, lang))

    story = []
    story.append(Paragraph("ShariahEase", ParagraphStyle("app", fontName="Helvetica-Bold", fontSize=24,
                                                           textColor=GREEN_DARK, alignment=TA_CENTER, leading=30, spaceAfter=4)))
    story.append(P(t["app_sub"], _style("sub", lang, 10, color=GRAY_TEXT, align=TA_CENTER, spaceAfter=8)))
    story.append(HRFlowable(width="100%", thickness=1.5, color=GREEN_MID, spaceAfter=10))
    story.append(P(t["title"], _style("title", lang, 16, bold=True, align=TA_CENTER, leading=24, spaceAfter=12)))

    info = [row(P(t["period"], cell), P(period, cell)), row(P(t["generated"], cell), P(shown_date(generated_on, lang), cell))]
    if issued_to:
        info.insert(0, row(P(t["issued_to"], cell), P(issued_to, cell)))
    info.append(row(P(t["currency"], cell), P("PKR", cell)))
    info_table = Table(info, colWidths=widths(4.2, 12.4))
    info_table.setStyle(TableStyle([
        ("ROWBACKGROUNDS", (0, 0), (-1, -1), [GREEN_LIGHT, WHITE]), ("GRID", (0, 0), (-1, -1), 0.5, GREEN_BORDER),
        ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))
    story += [info_table, Spacer(1, 0.5 * cm)]

    section = _style("section", lang, 11, bold=True, color=GREEN_DARK, spaceBefore=6, spaceAfter=6)

    # summary
    story.append(P(t["summary"], section))
    data = [row(P(t["kind"], head), P(t["entries"], head_num), P(t["amount"], head_num))]
    for ty in statement.types:
        label = ty.name_ur if rtl else ty.name_en
        data.append(row(P(label, cell), P(str(ty.count), cell_num), P(money(ty.total_paisa), cell_num)))
    data.append(row(P(t["total"], bold_cell), P(str(statement.count), bold_num), P(money(statement.total_paisa), bold_num)))
    story.append(table(data, widths(8.0, 3.0, 5.6), [("BACKGROUND", (0, -1), (-1, -1), GREEN_LIGHT)]))
    story.append(Spacer(1, 0.5 * cm))

    # calculator check
    zc = statement.zakat_check
    if zc is not None:
        story.append(P(t["calc_title"], section))
        if zc.is_zakat_due:
            lines = [(t["calc_due"].format(date=shown_date(zc.calculated_on, lang)), money(zc.zakat_due_paisa))]
        else:
            lines = [(t["calc_below"].format(date=shown_date(zc.calculated_on, lang)), money(zc.zakat_due_paisa))]
        lines.append((t["calc_paid"], money(zc.zakat_paid_paisa)))
        if zc.remaining_paisa:
            lines.append((t["calc_left"], money(zc.remaining_paisa)))
        if zc.overpaid_paisa:
            lines.append((t["calc_over"], money(zc.overpaid_paisa)))
        data = [row(P(label, cell), P(value, cell_num)) for label, value in lines]
        box = Table(data, colWidths=widths(12.0, 4.6))
        box.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), GREEN_LIGHT), ("GRID", (0, 0), (-1, -1), 0.5, GREEN_BORDER),
                                 ("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("TOPPADDING", (0, 0), (-1, -1), 5),
                                 ("BOTTOMPADDING", (0, 0), (-1, -1), 5)]))
        story.append(box)
        for line in t["calc_note"]:
            story.append(P(line, _style("calc_note", lang, 8.5, color=GRAY_TEXT, spaceBefore=2)))
        story.append(Spacer(1, 0.4 * cm))

    # entries
    story.append(P(t["list"], section))
    if not statement.entries:
        story.append(P(t["none"], _style("none", lang, 10, color=GRAY_TEXT)))
    else:
        data = [row(P(t["date"], head), P(t["kind"], head), P(t["paid_by"], head), P(t["amount"], head_num))]
        for e in statement.entries:
            data.append(row(P(shown_date(e.occurred_on, lang), cell), P(e.name_ur if rtl else e.name_en, cell),
                            P(t["pm"].get(e.payment_method, e.payment_method), cell), P(money(e.amount_paisa), cell_num)))
        story.append(table(data, widths(3.0, 5.0, 3.9, 4.7)))
        if statement.entries_truncated:
            story.append(P(t["truncated"].format(n=len(statement.entries)), _style("trunc", lang, 8.5, color=GRAY_TEXT, spaceBefore=4)))

    # disclaimer
    story += [Spacer(1, 0.6 * cm), HRFlowable(width="100%", thickness=0.5, color=GREEN_BORDER, spaceAfter=8)]
    for line in t["disclaimer"]:
        story.append(P(line, _style("disc", lang, 8, color=GRAY_TEXT, align=TA_CENTER, leading=12)))

    def footer(canvas, doc):
        canvas.saveState()
        text = t["footer"].format(date=shown_date(generated_on, lang), page=doc.page)
        canvas.setFillColor(GRAY_TEXT)
        if rtl:
            shown = visual(text, lang)
            canvas.setFont(URDU_LATIN, 8)
            x = A4[0] / 2
            # draw each run in its own font; `shown` is already in visual (left to right on the page) order
            parts = _ARABIC.split(shown)
            widths_ = [pdfmetrics.stringWidth(p, URDU_FONT if _ARABIC.fullmatch(p) else URDU_LATIN, 8) for p in parts if p]
            x -= sum(widths_) / 2
            for part in (p for p in parts if p):
                font = URDU_FONT if _ARABIC.fullmatch(part) else URDU_LATIN
                canvas.setFont(font, 8)
                canvas.drawString(x, 1.2 * cm, part)
                x += pdfmetrics.stringWidth(part, font, 8)
        else:
            canvas.setFont("Helvetica", 8)
            canvas.drawCentredString(A4[0] / 2, 1.2 * cm, text)
        canvas.restoreState()

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, leftMargin=2.2 * cm, rightMargin=2.2 * cm, topMargin=2.0 * cm,
                            bottomMargin=2.0 * cm, title=re.sub(r"\s+", " ", T[lang]["title"]), author="ShariahEase")
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buffer.getvalue()
